        private void ToggleLayoutSettings()
        {
            LobbySettingsPanel.Visible = !LobbySettingsPanel.Visible;

            if (LobbySettingsPanel.Visible)
                SidebarScroll.VScroll = 0;
        }

        private void UpdateCharacterInfo()
        {
            var characterName = _preferencesManager.Preferences?.SelectedCharacter?.Name ?? string.Empty;

            if (characterName != _lastCharacterName)
            {
                _lastCharacterName = characterName;
                CharacterNameLabel.Text = string.IsNullOrWhiteSpace(characterName)
                    ? Loc.GetString("lobby-character-name-none")
                    : characterName.ToUpperInvariant();
            }

            var playerCount = _playerManager.PlayerCount;
            if (playerCount != _lastPlayerCount)
            {
                _lastPlayerCount = playerCount;
                OnlineCountLabel.Text = Loc.GetString("lobby-online-count", ("count", playerCount));
            }
        }

        private void UpdatePlaytimePanel()
        {
            if (!_placements.TryGetValue(LobbyElement.Playtime, out var placement))
            {
                return;
            }

            PlaytimePanel.Visible = PlaytimeComment.Visible;

            if (placement == LobbyPlacement.Sidebar)
            {
                if (_sidebarPanels.TryGetValue(LobbyElement.Playtime, out var sidebarPanel))
                    sidebarPanel.Visible = PlaytimeComment.Visible;

                return;
            }

            if (!_floatingPanels.TryGetValue(LobbyElement.Playtime, out var wrapper) ||
                wrapper.Parent != FloatingPanelLayer)
            {
                return;
            }

            var wasVisible = wrapper.Visible;
            wrapper.Visible = PlaytimeComment.Visible;

            if (wasVisible != wrapper.Visible)
                _floatingLayoutDirty = true;
        }

        /// <summary>
        /// Shows a patron or server lobby message as a BlueMoon-style toast over the screen.
        /// </summary>
        public void SetLobbyMessage(string markup)
        {
            LobbyMessageLabel.SetMarkupPermissive(markup);
            LobbyMessagePanel.Visible = !string.IsNullOrWhiteSpace(markup);
        }

