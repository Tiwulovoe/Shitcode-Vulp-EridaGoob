        private void RefreshLayoutRows()
        {
            _updatingLayoutUi = true;
            LobbyLayoutRows.RemoveAllChildren();

            foreach (var info in LobbyLayoutConfig.Elements)
            {
                if (!info.CanScreen)
                    continue;

                var row = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    SeparationOverride = 6,
                };

                var label = new Label
                {
                    Text = Loc.GetString(info.NameLoc),
                    HorizontalExpand = true,
                    VerticalAlignment = VAlignment.Center,
                    ClipText = true,
                    FontColorOverride = EridaLobbyTheme.TextMuted,
                };

                var option = new OptionButton
                {
                    MinWidth = 112,
                };

                option.AddItem(Loc.GetString("lobby-layout-placement-sidebar"), (int) LobbyPlacement.Sidebar);
                option.AddItem(Loc.GetString("lobby-layout-placement-screen"), (int) LobbyPlacement.OnScreen);

                var placement = _placements.TryGetValue(info.Element, out var runtimePlacement)
                    ? runtimePlacement
                    : LobbyLayoutConfig.GetPlacement(_cfg, info.Element);

                option.TrySelectId((int) placement);
                option.OnItemSelected += args => OnLayoutOptionSelected(info.Element, args.Id, args.Button);
                EridaLobbyTheme.ApplyInput(option);

                row.AddChild(label);
                row.AddChild(option);
                LobbyLayoutRows.AddChild(row);
            }

            _updatingLayoutUi = false;
            _rowsNeedRefresh = false;
            UpdateOverflowLabel();
        }

        private void UpdateOverflowLabel()
        {
            var overflow = 0;

            foreach (var info in LobbyLayoutConfig.Elements)
            {
                if (LobbyLayoutConfig.GetPlacement(_cfg, info.Element) != LobbyPlacement.OnScreen)
                    continue;

                if (_placements.TryGetValue(info.Element, out var runtime) &&
                    runtime == LobbyPlacement.Sidebar)
                {
                    overflow++;
                }
            }

            LobbyLayoutOverflowLabel.Visible = overflow > 0;

            if (overflow > 0)
            {
                LobbyLayoutOverflowLabel.Text =
                    Loc.GetString("lobby-layout-overflow", ("count", overflow));
            }
        }

        private void OnLayoutOptionSelected(LobbyElement element, int id, OptionButton option)
        {
            if (_updatingLayoutUi)
                return;

            if (id < (int) LobbyPlacement.Sidebar || id > (int) LobbyPlacement.OnScreen)
                return;

            var placement = (LobbyPlacement) id;
            if (placement == LobbyPlacement.OnScreen && !LobbyLayoutConfig.CanScreen(element))
                return;

            // OptionButton does not update its own label on selection, so do it explicitly.
            // Guard against a possible OnItemSelected callback from SelectId itself.
            _updatingLayoutUi = true;
            option.SelectId(id);
            _updatingLayoutUi = false;

            LobbyLayoutConfig.SetPlacement(_cfg, element, placement);
            ApplyLayout();
            UpdateLayoutPresetIndicators();
        }

