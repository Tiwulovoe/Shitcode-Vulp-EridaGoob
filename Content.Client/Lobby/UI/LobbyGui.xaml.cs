        private void ApplyLayout()
        {
            _placements = new Dictionary<LobbyElement, LobbyPlacement>(LobbyLayoutConfig.GetAllPlacements(_cfg));

            foreach (var info in LobbyLayoutConfig.Elements)
            {
                if (!_elementPanels.TryGetValue(info.Element, out var panel))
                    continue;

                var placement = _placements[info.Element];

                if (placement == LobbyPlacement.Sidebar)
                {
                    if (_floatingPanels.TryGetValue(info.Element, out var oldFloating))
                        oldFloating.Orphan();

                    panel.Orphan();

                    var sidebarPanel = GetOrCreateSidebarPanel(info);
                    sidebarPanel.SetContent(panel);

                    if (sidebarPanel.Parent != SidebarContentHost)
                    {
                        sidebarPanel.Orphan();
                        SidebarContentHost.AddChild(sidebarPanel);
                    }

                    panel.Visible = true;
                    sidebarPanel.Visible = info.Element != LobbyElement.Playtime || PlaytimeComment.Visible;
                    continue;
                }

                // On screen: each element gets its own draggable floating panel.
                if (_sidebarPanels.TryGetValue(info.Element, out var oldSidebar))
                {
                    panel.Orphan();
                    oldSidebar.Orphan();
                }

                panel.Orphan();

                var wrapper = GetOrCreateFloatingPanel(info);
                wrapper.SetContent(panel);

                if (wrapper.Parent != FloatingPanelLayer)
                {
                    wrapper.Orphan();
                    FloatingPanelLayer.AddChild(wrapper);
                }

                panel.Visible = info.Element != LobbyElement.Playtime || PlaytimeComment.Visible;
                wrapper.Visible = panel.Visible;
            }

            ReorderSidebarContent();

            var chatPlacement = _placements[LobbyElement.Chat];
            var chatOnScreen = chatPlacement == LobbyPlacement.OnScreen;

            Chat.MinSize = chatOnScreen
                ? new Vector2(260, 160)
                : new Vector2(250, 170);
            Chat.VerticalExpand = true;
            ChatPanel.SetHeight = chatOnScreen ? 360f : 240f;
            ChatPanel.MaxHeight = chatOnScreen ? 360f : float.PositiveInfinity;
            ChatPanel.VerticalExpand = false;

            LinkBanner.Orientation = BoxContainer.LayoutOrientation.Vertical;

            _floatingLayoutDirty = true;
            _rowsNeedRefresh = true;

            if (FloatingPanelLayer.Size.X > 1f && FloatingPanelLayer.Size.Y > 1f)
                ArrangeFloatingPanels();
        }

        private void RetryOverflowedPanels()
        {
            foreach (var info in LobbyLayoutConfig.Elements)
            {
                if (LobbyLayoutConfig.GetPlacement(_cfg, info.Element) != LobbyPlacement.OnScreen)
                    continue;

                if (!_placements.TryGetValue(info.Element, out var runtime) ||
                    runtime != LobbyPlacement.Sidebar)
                {
                    continue;
                }

                if (!_elementPanels.TryGetValue(info.Element, out var panel))
                    continue;

                if (_sidebarPanels.TryGetValue(info.Element, out var sidebarPanel))
                {
                    panel.Orphan();
                    sidebarPanel.Orphan();
                }

                var wrapper = GetOrCreateFloatingPanel(info);
                panel.Orphan();
                wrapper.SetContent(panel);

                if (wrapper.Parent != FloatingPanelLayer)
                {
                    wrapper.Orphan();
                    FloatingPanelLayer.AddChild(wrapper);
                }

                panel.Visible = info.Element != LobbyElement.Playtime || PlaytimeComment.Visible;
                wrapper.Visible = panel.Visible;

                _placements[info.Element] = LobbyPlacement.OnScreen;
                _rowsNeedRefresh = true;
            }
        }

        private LobbySidebarPanel GetOrCreateSidebarPanel(LobbyElementInfo info)
        {
            if (_sidebarPanels.TryGetValue(info.Element, out var panel))
                return panel;

            panel = new LobbySidebarPanel(info.Element, Loc.GetString(info.NameLoc));
            _sidebarPanels[info.Element] = panel;
            return panel;
        }

        private LobbyFloatingPanel GetOrCreateFloatingPanel(LobbyElementInfo info)
        {
            if (_floatingPanels.TryGetValue(info.Element, out var wrapper))
                return wrapper;

            wrapper = new LobbyFloatingPanel(info.Element, info.Dock, Loc.GetString(info.NameLoc));
            _floatingPanels[info.Element] = wrapper;
            return wrapper;
        }

        private void ArrangeFloatingPanels()
        {
            var layerSize = FloatingPanelLayer.Size;
            if (layerSize.X <= 1f || layerSize.Y <= 1f)
                return;

            RetryOverflowedPanels();

            var maxWidth = MathF.Max(200f, layerSize.X - FloatingMargin * 2f);
            var entries = new List<FloatingPanelEntry>();
            var placed = new List<UIBox2>();

            foreach (var info in LobbyLayoutConfig.Elements)
            {
                if (!_placements.TryGetValue(info.Element, out var placement) ||
                    placement != LobbyPlacement.OnScreen)
                {
                    continue;
                }

                if (!_floatingPanels.TryGetValue(info.Element, out var wrapper) ||
                    wrapper.Parent != FloatingPanelLayer ||
                    !wrapper.Visible)
                {
                    continue;
                }

                var width = MathF.Min(GetFloatingWidth(info.Element), maxWidth);
                wrapper.SetWidth = width;

                if (info.Element == LobbyElement.Chat)
                {
                    var chatHeight = MathF.Min(360f, MathF.Max(160f, layerSize.Y - FloatingMargin * 2f - 24f));
                    ChatPanel.SetHeight = chatHeight;
                    ChatPanel.MaxHeight = chatHeight;
                    ChatPanel.VerticalExpand = false;
                }

                wrapper.Measure(new Vector2(width, float.PositiveInfinity));
                var size = wrapper.DesiredSize;
                if (size.X <= 0f || size.Y <= 0f)
                    continue;

                entries.Add(new FloatingPanelEntry(info, wrapper, size));
            }

            // Panels the player moved keep their position, but are still clamped and collision-checked.
            foreach (var entry in entries)
            {
                if (!entry.Wrapper.HasBeenMoved || entry.Wrapper.UserPosition == null)
                    continue;

                var position = LobbyFloatingPanel.ClampPosition(entry.Wrapper.UserPosition.Value, layerSize, entry.Size);

                if (!TryFindFreePosition(position, entry.Size, entry.Info.Dock, layerSize, placed, out var freePosition))
                {
                    OverflowToSidebar(entry);
                    continue;
                }

                entry.Wrapper.SetInitialPosition(freePosition);
                placed.Add(MakeRect(freePosition, entry.Size));
            }

            var topLeftY = FloatingMargin;
            var topRightY = FloatingMargin;
            var bottomLeftY = layerSize.Y - FloatingMargin;
            var bottomRightY = layerSize.Y - FloatingMargin;

            foreach (var element in FloatingPlacementPriority)
            {
                FloatingPanelEntry? selectedEntry = null;

                foreach (var candidateEntry in entries)
                {
                    if (candidateEntry.Info.Element != element)
                        continue;

                    selectedEntry = candidateEntry;
                    break;
                }

                if (selectedEntry is not { } entry)
                    continue;

                var wrapper = entry.Wrapper;
                if (wrapper.HasBeenMoved && wrapper.UserPosition != null)
                    continue;

                var size = entry.Size;
                Vector2 position;

                switch (entry.Info.Dock)
                {
                    case LobbyScreenDock.TopLeft:
                        position = new Vector2(FloatingMargin, topLeftY);
                        break;

                    case LobbyScreenDock.TopRight:
                        position = new Vector2(layerSize.X - FloatingMargin - size.X, topRightY);
                        break;

                    case LobbyScreenDock.BottomLeft:
                        position = new Vector2(FloatingMargin, bottomLeftY - size.Y);
                        break;

                    case LobbyScreenDock.BottomRight:
                        position = new Vector2(layerSize.X - FloatingMargin - size.X, bottomRightY - size.Y);
                        break;

                    default:
                        position = new Vector2(FloatingMargin, FloatingMargin);
                        break;
                }

                if (!TryFindFreePosition(position, size, entry.Info.Dock, layerSize, placed, out var freePosition))
                {
                    OverflowToSidebar(entry);
                    continue;
                }

                switch (entry.Info.Dock)
                {
                    case LobbyScreenDock.TopLeft:
                        topLeftY += size.Y + FloatingGap;
                        break;
                    case LobbyScreenDock.TopRight:
                        topRightY += size.Y + FloatingGap;
                        break;
                    case LobbyScreenDock.BottomLeft:
                        bottomLeftY -= size.Y + FloatingGap;
                        break;
                    case LobbyScreenDock.BottomRight:
                        bottomRightY -= size.Y + FloatingGap;
                        break;
                }

                wrapper.SetInitialPosition(freePosition);
                placed.Add(MakeRect(freePosition, size));
            }

            _floatingLayoutDirty = false;
        }

        private static float GetFloatingWidth(LobbyElement element)
        {
            return element switch
            {
                LobbyElement.QuickActions => 300f,
                LobbyElement.Balance => 220f,
                LobbyElement.ServerInfo => 340f,
                LobbyElement.CharacterPreview => 300f,
                LobbyElement.Chat => 320f,
                LobbyElement.MusicPlayer => 340f,
                LobbyElement.Links => 300f,
                LobbyElement.Playtime => 340f,
                _ => 300f,
            };
        }

        private static bool TryFindFreePosition(
            Vector2 preferred,
            Vector2 size,
            LobbyScreenDock dock,
            Vector2 layerSize,
            List<UIBox2> placed,
            out Vector2 result)
        {
            var minX = FloatingMargin;
            var minY = FloatingMargin;
            var maxX = layerSize.X - FloatingMargin - size.X;
            var maxY = layerSize.Y - FloatingMargin - size.Y;

            if (maxX < minX || maxY < minY)
            {
                result = default;
                return false;
            }

            var clampedPreferred = LobbyFloatingPanel.ClampPosition(preferred, layerSize, size);
            if (IsFree(clampedPreferred, size, placed))
            {
                result = clampedPreferred;
                return true;
            }

            // Search only along the two screen edges that meet at the preferred corner.
            // If neither edge has room, the caller moves the panel to the sidebar.
            const float step = 16f;
            var horizontalSteps = (int) MathF.Ceiling((maxX - minX) / step);
            var verticalSteps = (int) MathF.Ceiling((maxY - minY) / step);

            var right = dock is LobbyScreenDock.TopRight or LobbyScreenDock.BottomRight;
            var bottom = dock is LobbyScreenDock.BottomLeft or LobbyScreenDock.BottomRight;

            for (var i = 0; i <= verticalSteps; i++)
            {
                var y = bottom ? MathF.Max(minY, maxY - i * step) : MathF.Min(maxY, minY + i * step);
                var x = right ? maxX : minX;

                var candidate = new Vector2(x, y);
                if (!IsFree(candidate, size, placed))
                    continue;

                result = candidate;
                return true;
            }

            for (var i = 0; i <= horizontalSteps; i++)
            {
                var x = right ? MathF.Max(minX, maxX - i * step) : MathF.Min(maxX, minX + i * step);
                var y = bottom ? maxY : minY;

                var candidate = new Vector2(x, y);
                if (!IsFree(candidate, size, placed))
                    continue;

                result = candidate;
                return true;
            }

            result = default;
            return false;
        }

        private static bool IsFree(Vector2 position, Vector2 size, List<UIBox2> placed)
        {
            var rect = MakeRect(position, size);

            foreach (var other in placed)
            {
                if (rect.Intersects(other))
                    return false;
            }

            return true;
        }

        private void OverflowToSidebar(FloatingPanelEntry entry)
        {
            var wrapper = entry.Wrapper;
            var panel = _elementPanels[entry.Info.Element];

            panel.Orphan();

            var sidebarPanel = GetOrCreateSidebarPanel(entry.Info);
            sidebarPanel.SetContent(panel);

            if (sidebarPanel.Parent != SidebarContentHost)
            {
                sidebarPanel.Orphan();
                SidebarContentHost.AddChild(sidebarPanel);
            }

            panel.Visible = true;
            sidebarPanel.Visible = entry.Info.Element != LobbyElement.Playtime || PlaytimeComment.Visible;
            ReorderSidebarContent();

            wrapper.Orphan();
            wrapper.RemoveContent();
            wrapper.Visible = false;

            _placements[entry.Info.Element] = LobbyPlacement.Sidebar;
            _rowsNeedRefresh = true;
        }

        private void ReorderSidebarContent()
        {
            var index = 0;

            foreach (var info in LobbyLayoutConfig.Elements)
            {
                if (!_sidebarPanels.TryGetValue(info.Element, out var sidebarPanel) ||
                    sidebarPanel.Parent != SidebarContentHost)
                {
                    continue;
                }

                sidebarPanel.SetPositionInParent(index++);
            }
        }

        private static UIBox2 MakeRect(Vector2 position, Vector2 size)
        {
            return new UIBox2(position, position + size);
        }

